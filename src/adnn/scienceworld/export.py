"""Minimal ScienceWorld record exporter (ADR-0009; docs/34 §4).

Turns the ScienceWorld candidates whose evidence is complete into dataset records. Labels are
**not** computed here: they are read from the frozen ``sw-admission-2`` decisions and kept
only if every tier-G requirement (ADR-0006 D3) is evidenced in the stored results:

* outcome ``eligible_reversible``, or ``eligible_partially_reversible`` whose residual is
  protected by an admissible certificate;
* R5 replication in a second fresh process (``results/phase4h/comparison.json``);
* the Phase 4F query-order audit with identical transitions (``measurement_audit.json``);
* measurement symmetry, not affected (``results/phase5a/symmetry_summary.json``);
* rubric sensitivity, outcome unchanged (``comparison.json``).

Per-horizon labels: the witness restores (exactly or approximately) within ``d`` steps, so
the label is resolved for every horizon ``h >= d``. Below ``d`` a failed search is not
irreversibility, so the horizon is unresolved; a case with any unresolved horizon cannot be
written with complete ``labels_by_horizon`` and is reported, not exported.

``state_text`` is regenerated by replaying the pinned recipe and reading ``look`` and
``inventory``; the start-state fingerprint must equal the evidence's ``s0_raw_fingerprint``
and must not change by observing. Requires the pinned runtime (docs/18).
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Callable, Mapping
from pathlib import Path
from typing import Any

from adnn.dataset.prompting import PromptInputs
from adnn.dataset.prompting_v11 import (
    PROMPT_BUILDER_VERSION,
    build_probe_prompt,
    build_stated_prompt,
)
from adnn.dataset.schema import HORIZONS, sha256_text, stable_json

EXPORTER_VERSION = "sw-export-1.0"
DECISION_RULE = "sw-admission-2"
SW_PARTIAL_RULE = (
    "sw-admission-2 (ADR-0006 D3, ADR-0005): eligible partially reversible with a positive "
    "approximate witness and a residual protected by an admissible certificate"
)
COMPLETE_CASES: tuple[str, ...] = (
    "h4-burn-chair-water-near",
    "h4-burn-painting-water-near",
    "h4-connect-battery-wire",
    "h4-move-cup-to-table",
    "h4-open-fridge",
)
EXCLUDED_CASES: dict[str, str] = {
    "ctrl-open-cupboard": "eligible, but no R5 replication, query-order audit or rubric check",
    "registry-miss-connect-v2": "eligible, but no R5 replication, query-order audit or rubric "
    "check",
}
EVIDENCE_DIR = Path("results/phase4h/main")
COMPARISON = Path("results/phase4h/comparison.json")
MEASUREMENT = Path("results/phase4h/measurement_audit.json")
SYMMETRY = Path("results/phase5a/symmetry_summary.json")
LABEL_OF = {
    "eligible_reversible": "reversible",
    "eligible_partially_reversible": "partially_reversible",
}
TASK_TEXT = {
    "1-1": "You are in a house with a kitchen. Work with the objects around you.",
    "3-1": "You are in a house with a workshop. Work with the objects around you.",
}
SW_TOOLS: list[dict[str, Any]] = [
    {
        "name": "scienceworld_action",
        "description": "Perform one ScienceWorld action, typed as a short command "
        "(e.g. 'open fridge', 'move cup to table').",
        "parameters": {
            "type": "object",
            "properties": {"command": {"type": "string", "description": "The command."}},
            "required": ["command"],
            "additionalProperties": False,
        },
    }
]
SW_TOOL_SET_ID = "ts-scienceworld-1"


def sha256_path(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def gate(case_id: str) -> dict[str, Any]:
    """Every tier-G evidence requirement for one case, read from stored results only."""
    doc = _load(EVIDENCE_DIR / f"{case_id}.json")
    ev, dec = doc["evidence"], doc["decision"]
    comp, meas, sym = _load(COMPARISON), _load(MEASUREMENT), _load(SYMMETRY)
    outcome = dec["outcome"]
    cert = dec.get("certificate") or {}
    residual = dec["witness"].get("residual", [])
    protected = {f for c in cert.get("claims", []) for _, f in c.get("protects", [])}
    m = meas.get(case_id, {}).get("conditions", {})
    checks = {
        "decision_rule": dec["decision_rule_version"] == DECISION_RULE,
        "eligible": outcome in LABEL_OF and not dec["quarantined"],
        "evidence_complete": ev["status"] == "complete" and ev["replay"]["verified"],
        "r5_replicated": comp["replication"].get(case_id, {}).get("replicated") is True,
        "query_order_audit": bool(m) and all(c.get("transitions_equal_all_k") for c in m.values()),
        "symmetry_unaffected": sym["cases"].get(case_id, {}).get("affected") is False,
        "rubric_unchanged": comp["rubric_sensitivity"].get(case_id, {}).get("changed") is False,
        "partial_residual_certified": outcome != "eligible_partially_reversible"
        or (cert.get("admissible") is True
            and all(r.split(".", 1)[1] in protected for r in residual)),
    }  # fmt: skip
    depth = len(dec["witness"]["path"])
    labels = {str(h): (LABEL_OF.get(outcome) if h >= depth else None) for h in HORIZONS}
    return {
        "case_id": case_id,
        "checks": checks,
        "passed": all(checks.values()),
        "witness_depth": depth,
        "labels_by_horizon": labels,
        "unresolved_horizons": [h for h, v in labels.items() if v is None],
        "evidence_sha256": sha256_path(EVIDENCE_DIR / f"{case_id}.json"),
        "family_id": ev["case"]["family_id"],
        "task": ev["case"]["task"],
        "target": ev["target"]["action"],
        "recipe": ev["provenance"]["recipe"],
        "s0_raw_fingerprint": ev["replay"]["s0_raw_fingerprint"],
        "decision": {k: dec[k] for k in ("outcome", "witness", "certificate")},
    }


def observe(g: Mapping[str, Any], session_factory: Callable[[int], Any] | None = None) -> str:
    """Replay the pinned recipe and return ``look`` + ``inventory`` at S0, after checking
    the start-state fingerprint against the evidence (before and after observing)."""
    from adnn.scienceworld.canonical import capture_state
    from adnn.scienceworld.env import ScienceWorldSession
    from adnn.scienceworld.replay import ReplayRecipe, run_recipe

    recipe = ReplayRecipe.from_dict(g["recipe"])
    factory = session_factory or (lambda n: ScienceWorldSession(None, step_limit=n))
    with factory(recipe.step_limit) as session:
        run_recipe(session, recipe)
        before = capture_state(session).raw.fingerprint
        text = session.look().strip() + "\n" + session.inventory().strip()
        after = capture_state(session).raw.fingerprint
    if before != g["s0_raw_fingerprint"] or after != before:
        raise RuntimeError(f"{g['case_id']}: S0 fingerprint does not match the evidence")
    return text


def make_record(g: Mapping[str, Any], state_text: str, dataset_version: str) -> dict[str, Any]:
    labels = g["labels_by_horizon"]
    task_text = TASK_TEXT[g["task"]]
    action_text = g["target"]
    inputs = PromptInputs(task_text, state_text, tuple(SW_TOOLS))
    witness = g["decision"]["witness"]
    exact = witness["canonical_level"] == "exact"
    depth = g["witness_depth"]
    return {
        "id": f"sw-{g['case_id']}",
        "environment": "scienceworld",
        "state_text": state_text,
        "action_text": action_text,
        "label": labels[str(max(HORIZONS))],
        "horizon": max(HORIZONS),
        "source": "scienceworld_bfs",
        "scenario_id": "sw-grp-" + g["family_id"],
        "template_id": "sw-" + g["family_id"],
        "pair_id": None,
        "pivot": None,
        "labels_by_horizon": dict(labels),
        "restore_depth": depth if exact else None,
        "approx_restore_depth": depth,
        "task_text": task_text,
        "tool_set_id": SW_TOOL_SET_ID,
        "action_verb": action_text.split()[0],
        "action_call": None,
        "state_struct": None,
        "render_style": "prose",  # native ScienceWorld observation text
        "label_rationale": f"{DECISION_RULE}: {g['decision']['outcome']}; witness "
        f"{witness['path']} ({witness['canonical_level']}); residual {witness['residual']}",
        "label_provisional": False,
        "provisional_reasons": [],
        "tier": "G",
        "sensitivity_group": None,
        "meta": {
            "domain": "scienceworld",
            "example_kind": "non_pair",
            "case_id": g["case_id"],
            "evidence_sha256": g["evidence_sha256"],
            "s0_raw_fingerprint": g["s0_raw_fingerprint"],
            "recipe": g["recipe"],
            "decision": g["decision"],
            "evidence_checks": g["checks"],
            "partial_definition": SW_PARTIAL_RULE,
            "exporter_version": EXPORTER_VERSION,
            "prompt_builder_version": PROMPT_BUILDER_VERSION,
            "probe_prompt_sha256": build_probe_prompt(inputs, action_text).prompt_sha256,
            "stated_prompt_sha256": build_stated_prompt(inputs, action_text).prompt_sha256,
        },
        "dataset_version": dataset_version,
    }


def export(
    dataset_version: str, session_factory: Callable[[int], Any] | None = None
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Records for every complete case that passes its gate; a report for all of them."""
    records, report = [], {"cases": {}, "excluded": dict(EXCLUDED_CASES)}
    for case_id in COMPLETE_CASES:
        g = gate(case_id)
        entry = {k: g[k] for k in ("checks", "passed", "witness_depth", "unresolved_horizons")}
        if g["passed"] and not g["unresolved_horizons"]:
            records.append(make_record(g, observe(g, session_factory), dataset_version))
            entry["exported"] = True
        else:
            entry["exported"] = False
        report["cases"][case_id] = entry
    report["records_sha256"] = sha256_text(stable_json(records))
    return records, report


def validate_record(r: Mapping[str, Any]) -> list[str]:
    """Re-check a ScienceWorld record against the stored evidence (no simulator needed)."""
    errors = []
    case = r["meta"].get("case_id")
    if case not in COMPLETE_CASES:
        return [f"{r['id']}: case {case!r} is not a complete-evidence case"]
    g = gate(case)
    if not g["passed"]:
        errors.append(f"{r['id']}: evidence gate fails: {g['checks']}")
    if r["meta"].get("evidence_sha256") != g["evidence_sha256"]:
        errors.append(f"{r['id']}: evidence file hash differs")
    if r["labels_by_horizon"] != g["labels_by_horizon"]:
        errors.append(f"{r['id']}: labels differ from the frozen decision")
    if r["tier"] != "G" or r["provisional_reasons"]:
        errors.append(f"{r['id']}: ScienceWorld record must be tier G without reasons")
    if r["action_text"] != g["target"]:
        errors.append(f"{r['id']}: action_text differs from the evidence target")
    return errors
